detailTranslations.en.resumeDownload = 'Download résumé';

let detailLanguage = localStorage.getItem('site-language') === 'en' ? 'en' : 'zh';
const detailLanguageButton = document.querySelector('.language-toggle');
const detailThemeButton = document.querySelector('.theme-toggle');
const detailThemeLabel = document.querySelector('[data-theme-label]');

const updateDetailThemeLabel = () => {
  const isDark = document.documentElement.dataset.theme === 'dark';
  detailThemeLabel.textContent = detailLanguage === 'zh' ? (isDark ? '亮色' : '暗色') : (isDark ? 'Light' : 'Dark');
};

const applyDetailLanguage = (language) => {
  const copy = detailTranslations[language];
  detailLanguage = language;
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  document.title = copy.title;
  document.querySelector('meta[name="description"]').content = copy.description;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((element) => element.alt = copy[element.dataset.i18nAlt]);
  detailLanguageButton.textContent = language === 'zh' ? 'EN' : '中文';
  detailLanguageButton.setAttribute('aria-label', copy.languageAria);
  detailThemeButton.setAttribute('aria-label', copy.themeAria);
  updateDetailThemeLabel();
};

detailLanguageButton.addEventListener('click', () => {
  const next = detailLanguage === 'zh' ? 'en' : 'zh';
  localStorage.setItem('site-language', next);
  applyDetailLanguage(next);
});

detailThemeButton.addEventListener('click', () => {
  const next = document.documentElement.dataset.theme === 'dark' ? 'light' : 'dark';
  document.documentElement.dataset.theme = next;
  localStorage.setItem('site-theme', next);
  updateDetailThemeLabel();
});

applyDetailLanguage(detailLanguage);

const progress = document.querySelector('.progress i');
const updateProgress = () => {
  const available = document.documentElement.scrollHeight - window.innerHeight;
  progress.style.width = `${available > 0 ? (window.scrollY / available) * 100 : 0}%`;
};
window.addEventListener('scroll', updateProgress, { passive: true });
updateProgress();

const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add('visible');
      observer.unobserve(entry.target);
    }
  });
}, { threshold: 0.12 });
document.querySelectorAll('.reveal').forEach((element) => observer.observe(element));
